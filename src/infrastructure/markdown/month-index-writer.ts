import { readdir, rm, rmdir } from "node:fs/promises";
import { join } from "node:path";
import { monthDoc } from "../../domain/format";
import type { MonthKey } from "../../domain/task";
import { atomicWrite, isNotFound, readIfExists } from "../fs/files";
import { parseDayFile } from "./day-codec";

export const INDEX_FILE = "index.md";
const DAY_FILE = /^(\d{4}-\d{2}-\d{2})\.md$/;

/** Regenerates `<month>/index.md`: the whole month in one clean, copyable file. */
export class MonthIndexWriter {
  constructor(private readonly root: string) {}

  async rebuild(month: MonthKey): Promise<void> {
    const dir = join(this.root, month);
    const names = await readdir(dir).catch((e) =>
      isNotFound(e) ? [] : Promise.reject(e),
    );
    const days = names
      .map((n) => DAY_FILE.exec(n)?.[1])
      .filter((d): d is string => !!d)
      .sort();
    const loaded = await Promise.all(
      days.map(async (day) => ({
        day,
        tasks: parseDayFile(
          (await readIfExists(join(dir, `${day}.md`))) ?? "",
          day,
        ).tasks,
      })),
    );
    const indexPath = join(dir, INDEX_FILE);
    if (!loaded.some((d) => d.tasks.length)) {
      await rm(indexPath, { force: true });
      await rmdir(dir).catch(() => {}); // only succeeds when nothing else lives there
      return;
    }
    const doc = monthDoc(month, loaded).replace(
      "\n\n",
      "\n\n<!-- Generated by tasklog from the day files. Edits here are overwritten. -->\n\n",
    );
    await atomicWrite(indexPath, doc);
  }
}
